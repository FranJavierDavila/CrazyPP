def esc(s):
    return s.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')


def heading(num, texto):
    """H1 con ancla de TOC (nivel 0)."""
    key = 'h_' + hashlib.md5(f'{num}-{texto}'.encode()).hexdigest()[:8]
    p = Paragraph(f'<a name="{key}"/><b>{num} · {texto}</b>', h1)
    p.bookmark_name = key
    p.bookmark_level = 0
    p.bookmark_text = f'{num} · {texto}'
    p.bookmark_key = key
    return p


def sub(num, texto, nivel=1):
    key = 's_' + hashlib.md5(f'{num}-{texto}'.encode()).hexdigest()[:8]
    p = Paragraph(f'<a name="{key}"/><b>{num} {texto}</b>', h2)
    p.bookmark_name = key
    p.bookmark_level = nivel
    p.bookmark_text = f'{num} {texto}'
    p.bookmark_key = key
    return p


