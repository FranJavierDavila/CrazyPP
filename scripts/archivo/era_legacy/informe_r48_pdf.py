class TocDocTemplate(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if hasattr(flowable, 'bookmark_name'):
            level = getattr(flowable, 'bookmark_level', 0)
            text = getattr(flowable, 'bookmark_text', '')
            key = getattr(flowable, 'bookmark_key', '')
            self.notify('TOCEntry', (level, text, self.page, key))


def heading(text, style=st_h1, level=0):
    key = 'h_' + hashlib.md5(text.encode()).hexdigest()[:8]
    p = Paragraph(f'<a name="{key}"/><b>{text}</b>', style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p


def tabla(filas, anchos_rel, header=True, align_center_cols=()):
    """Tabla con anchos proporcionales al ancho disponible y celdas Paragraph."""
    disp = A4[0] - 2 * 18 * mm
    anchos = [a * disp for a in anchos_rel]
    datos = []
    for i, fila in enumerate(filas):
        celda_fila = []
        for j, celda in enumerate(fila):
            if i == 0 and header:
                celda_fila.append(Paragraph(f'<b>{celda}</b>', st_cell_h))
            else:
                st = st_cell_c if j in align_center_cols else st_cell
                celda_fila.append(Paragraph(str(celda), st))
        datos.append(celda_fila)
    t = Table(datos, colWidths=anchos, hAlign='CENTER', repeatRows=1 if header else 0)
    estilo = [
        ('GRID', (0, 0), (-1, -1), 0.4, BORDER),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
    ]
    if header:
        estilo.append(('BACKGROUND', (0, 0), (-1, 0), HEADER_FILL))
        for i in range(1, len(datos)):
            estilo.append(('BACKGROUND', (0, i), (-1, i),
                           colors.white if i % 2 == 1 else TABLE_STRIPE))
    t.setStyle(TableStyle(estilo))
    return t


