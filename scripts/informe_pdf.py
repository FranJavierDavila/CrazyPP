MAX_KEEP = A4[1] * 0.4

def seguro(elems):
    total = 0
    for e in elems:
        _, h = e.wrap(ANCHO, A4[1])
        total += h
    if total <= MAX_KEEP:
        return [KeepTogether(elems)]
    if len(elems) >= 2:
        return [KeepTogether(elems[:2])] + list(elems[2:])
    return list(elems)


def tabla(data, ratios, header=True):
    widths = [r * ANCHO for r in ratios]
    t = Table(data, colWidths=widths, hAlign='CENTER', repeatRows=1 if header else 0)
    est = [
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('GRID', (0, 0), (-1, -1), 0.5, BORDER),
        ('LEFTPADDING', (0, 0), (-1, -1), 7),
        ('RIGHTPADDING', (0, 0), (-1, -1), 7),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
    ]
    if header:
        est.append(('BACKGROUND', (0, 0), (-1, 0), HEADER_FILL))
        for i in range(1, len(data)):
            est.append(('BACKGROUND', (0, i), (-1, i),
                        TABLE_STRIPE if i % 2 else colors.white))
    t.setStyle(TableStyle(est))
    return t


