def tabla(data, ratios, alineaciones=None, font_size=9, cabecera=True):
    """Tabla con celdas Paragraph, anchos proporcionales y cebra."""
    colw = [r * AVAIL_W for r in ratios]
    assert abs(sum(ratios) - 1.0) < 1e-6, 'ratios deben sumar 1'
    filas = []
    for i, fila in enumerate(data):
        out = []
        for j, celda in enumerate(fila):
            if isinstance(celda, (Paragraph, Image, Table)):
                out.append(celda)
                continue
            if i == 0 and cabecera:
                out.append(Paragraph('<b>%s</b>' % celda, TH))
            else:
                al = (alineaciones or ['L'] * len(fila))[j]
                st = TDC if al == 'C' else TD
                if font_size != 9:
                    st = ParagraphStyle('td%d%d' % (i, j), parent=st,
                                        fontSize=font_size,
                                        leading=font_size + 3.5)
                out.append(Paragraph(str(celda), st))
        filas.append(out)
    t = Table(filas, colWidths=colw, hAlign='CENTER', repeatRows=1 if cabecera else 0)
    estilos = [
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
        ('GRID', (0, 0), (-1, -1), 0.5, BORDER),
    ]
    if cabecera:
        estilos.append(('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR))
        for i in range(1, len(data)):
            estilos.append(('BACKGROUND', (0, i), (-1, i),
                            TABLE_ROW_ODD if i % 2 else TABLE_ROW_EVEN))
    t.setStyle(TableStyle(estilos))
    return t


def callouts(story, stats):
    """Fila de 2-4 cajas de métrica (Data-to-Ink del brief)."""
    n = len(stats)
    caja_w = (AVAIL_W - (n - 1) * 12) / n
    celdas = []
    for grande, etiqueta in stats:
        inner = Table([[Paragraph('<b>%s</b>' % grande, STAT_BIG)],
                       [Paragraph(etiqueta, STAT_LBL)]],
                      colWidths=[caja_w - 2])
        inner.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), CARD_BG),
            ('BOX', (0, 0), (-1, -1), 1, ACCENT),
            ('TOPPADDING', (0, 0), (-1, 0), 8),
            ('BOTTOMPADDING', (0, 1), (-1, 1), 8),
            ('TOPPADDING', (0, 1), (-1, 1), 2),
            ('BOTTOMPADDING', (0, 0), (-1, 0), 2),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ]))
        celdas.append(inner)
    fila = Table([celdas], colWidths=[caja_w + (12 if i < n - 1 else 0)
                                      for i in range(n)], hAlign='CENTER')
    fila.setStyle(TableStyle([
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('LEFTPADDING', (0, 0), (-1, -1), 0),
        ('RIGHTPADDING', (0, 0), (-1, -1), 12),
        ('RIGHTPADDING', (-1, 0), (-1, -1), 0),
        ('TOPPADDING', (0, 0), (-1, -1), 0),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 0),
    ]))
    story.append(Spacer(1, 6))
    story.append(KeepTogether(fila))
    story.append(Spacer(1, 10))


def figura(path, caption, max_h=250):
    img = PILImage.open(path)
    ow, oh = img.size
    ratio = min(AVAIL_W / ow, max_h / oh, 1.0)
    story_img = Image(path, width=ow * ratio, height=oh * ratio)
    story_img.hAlign = 'CENTER'
    return story_img, Paragraph(caption, CAPTION)


